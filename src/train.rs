/// Count image files in a directory (recursive).
fn count_images(dir: &Path) -> Result<usize, String> {
    if !dir.exists() {
        return Ok(0);
    }
    let mut count = 0;
    for entry in std::fs::read_dir(dir).map_err(|e| format!("Cannot read '{:?}': {e}", dir))? {
        let entry = entry.map_err(|e| format!("Read entry: {e}"))?;
        let ext = entry
            .path()
            .extension()
            .and_then(|e| e.to_str())
            .unwrap_or("")
            .to_lowercase();
        if ["jpg", "jpeg", "png", "bmp"].contains(&ext.as_str()) {
            count += 1;
        }
    }
    Ok(count)
}

/// Spot-check label files in a directory, each line must parse as 5 floats.
fn validate_labels(dir: &Path) -> Result<(), String> {
    for entry in std::fs::read_dir(dir).map_err(|e| format!("Cannot read '{:?}': {e}", dir))? {
        let entry = entry.map_err(|e| format!("Read entry: {e}"))?;
        let path = entry.path();
        if path.extension().and_then(|e| e.to_str()) != Some("txt") {
            continue;
        }
        let content =
            std::fs::read_to_string(&path).map_err(|e| format!("Cannot read '{:?}': {e}", path))?;
        for (lineno, line) in content.lines().enumerate() {
            let trimmed = line.trim();
            if trimmed.is_empty() || trimmed.starts_with('#') {
                continue;
            }
            let parts: Vec<&str> = trimmed.split_whitespace().collect();
            if parts.len() != 5 {
                return Err(format!(
                    "'{:?}' line {}: expected 5 fields, got {}",
                    path,
                    lineno + 1,
                    parts.len()
                ));
            }
            for (i, p) in parts.iter().enumerate() {
                p.parse::<f32>()
                    .map_err(|_| format!("'{:?}' line {} field {}: not a float", path, lineno + 1, i + 1))?;
            }
        }
    }
    Ok(())
}

/// Find a working Python 3 interpreter.
fn find_python() -> Result<String, String> {
    for candidate in &["python3", "python"] {
        let output = std::process::Command::new(candidate)
            .arg("--version")
            .output();
        if let Ok(out) = output {
            if out.status.success() {
                return Ok(candidate.to_string());
            }
        }
    }
    Err("No Python 3 interpreter found. Install Python 3 on the cloud GPU VM.".into())
}

/// Check if ultralytics is importable.
fn check_ultralytics(python: &str) -> Result<(), String> {
    let output = std::process::Command::new(python)
        .args(["-c", "import ultralytics; print(ultralytics.__version__)"])
        .output()
        .map_err(|e| format!("Failed to check ultralytics: {e}"))?;

    if output.status.success() {
        let version = String::from_utf8_lossy(&output.stdout).trim().to_string();
        log::info!("ultralytics {} found", version);
        Ok(())
    } else {
        log::warn!("ultralytics not found. Will install automatically.");
        Ok(())
    }
}

/// Check if ultralytics is installed (returns false if not).
fn ultralytics_installed(python: &str) -> Result<bool, String> {
    let output = std::process::Command::new(python)
        .args(["-c", "import ultralytics"])
        .output()
        .map_err(|e| format!("Failed to check ultralytics: {e}"))?;
    Ok(output.status.success())
}

// ─────────────────────────────────────────────────────────────────────────────
//  Minimal deterministic PRNG (for reproducible shuffle)
// ─────────────────────────────────────────────────────────────────────────────

struct SimpleRng(u64);

impl SimpleRng {
    fn new(seed: u64) -> Self {
        Self(seed)
    }

    fn next(&mut self) -> u64 {
        // xorshift64*
        self.0 ^= self.0 >> 12;
        self.0 ^= self.0 << 25;
        self.0 ^= self.0 >> 27;
        self.0.wrapping_mul(0x2545_f491_4f6c_dd1d)
    }
}

