#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;

    fn create_test_dataset(dir: &Path) {
        let img_dir = dir.join("images").join("train");
        let lbl_dir = dir.join("labels").join("train");
        fs::create_dir_all(&img_dir).unwrap();
        fs::create_dir_all(&lbl_dir).unwrap();

        // Create one dummy image and label.
        let img_path = img_dir.join("test_000001.jpg");
        let img = image::RgbImage::new(100, 100);
        img.save(&img_path).unwrap();

        let lbl_path = lbl_dir.join("test_000001.txt");
        fs::write(&lbl_path, "0 0.5 0.5 0.2 0.2\n3 0.8 0.5 0.3 0.3\n").unwrap();
    }

    #[test]
    fn test_dataset_open_valid() {
        let dir = std::env::temp_dir().join("civicsense_test_open");
        let _ = fs::remove_dir_all(&dir);
        create_test_dataset(&dir);

        let ds = Dataset::open(&dir).expect("Dataset should open");
        assert_eq!(ds.train_count, 1);
        assert_eq!(ds.val_count, 0);
        assert_eq!(ds.num_classes, 7);

        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn test_dataset_open_missing_root() {
        let result = Dataset::open(Path::new("/nonexistent/path"));
        assert!(result.is_err());
    }

    #[test]
    fn test_dataset_yaml_generation() {
        let dir = std::env::temp_dir().join("civicsense_test_yaml");
        let _ = fs::remove_dir_all(&dir);
        create_test_dataset(&dir);
        let ds = Dataset::open(&dir).unwrap();

        let yaml_path = dir.join("dataset.yaml");
        ds.write_yaml(&yaml_path).unwrap();

        let content = fs::read_to_string(&yaml_path).unwrap();
        assert!(content.contains("nc: 7"));
        assert!(content.contains("stop_sign"));
        assert!(content.contains("intersection_zone"));

        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn test_validate_labels_valid() {
        let dir = std::env::temp_dir().join("civicsense_test_labels");
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();

        let lbl_path = dir.join("test.txt");
        fs::write(&lbl_path, "0 0.5 0.5 0.2 0.2\n3 0.8 0.5 0.3 0.3\n").unwrap();
        // Should not panic.
        validate_labels(&dir).unwrap();

        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn test_validate_labels_invalid() {
        let dir = std::env::temp_dir().join("civicsense_test_bad_labels");
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();

        let lbl_path = dir.join("bad.txt");
        fs::write(&lbl_path, "0 0.5 0.5 0.2\n").unwrap(); // only 4 fields
        assert!(validate_labels(&dir).is_err());

        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn test_label_validate_with_missing_file_not_crashing() {
        // Non-existent dir should not crash (read_dir will error).
        let result = validate_labels(Path::new("/tmp/nonexistent_labels_xyz"));
        assert!(result.is_err());
    }

    #[test]
    fn test_split_creates_train_val() {
        let source = std::env::temp_dir().join("civicsense_test_split_source");
        let dest = std::env::temp_dir().join("civicsense_test_split_dest");
        let _ = fs::remove_dir_all(&source);
        let _ = fs::remove_dir_all(&dest);
        fs::create_dir_all(&source).unwrap();

        // Create 6 labelled image pairs.
        for i in 1..=6 {
            let img_path = source.join(format!("frame_{:06}.jpg", i));
            let img = image::RgbImage::new(100, 100);
            img.save(&img_path).unwrap();
            let lbl_path = source.join(format!("frame_{:06}.txt", i));
            fs::write(&lbl_path, "0 0.5 0.5 0.2 0.2\n").unwrap();
        }

        let ds = Dataset::split(&source, &dest, 0.2).expect("Split should work");
        assert_eq!(ds.train_count + ds.val_count, 6);

        let _ = fs::remove_dir_all(&source);
        let _ = fs::remove_dir_all(&dest);
    }
}
