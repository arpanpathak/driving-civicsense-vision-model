//! # 🛑 Intersection Module
//!
//! Detects stop sign proximity, deceleration compliance, and intersection
//! occupancy to prevent "blocking the box" violations.
//!
//! ## Features
//!
//! - **Stop sign detection** — estimates distance via pinhole model and
//!   raises a violation alert if ego speed is too high at close range.
//! - **Blocked intersection** — measures how much of the forward view is
//!   occupied by vehicles; fires an alert if occupancy exceeds 30% while
//!   the ego vehicle is moving fast enough to enter the box.
//!
//! ## Status
//!
//! Core logic is functional.  The BEV occupancy grid and deceleration
//! profiling are placeholders — calibration with real camera extrinsics
//! will improve accuracy.

use crate::config::IntersectionConfig;
use crate::detection::yolo::Detection;
use crate::utils::geometry::estimate_distance;

// ─────────────────────────────────────────────────────────────────────────────
//  IntersectionAlert
// ─────────────────────────────────────────────────────────────────────────────

/// An alert generated by the intersection analyzer.
///
/// Two variants cover the two main violation types this module detects.
#[derive(Debug, Clone)]
pub enum IntersectionAlert {
    /// The ego vehicle is approaching a stop sign too fast.
    StopSignViolation {
        /// Confidence of the stop-sign detection (0.0 – 1.0).
        confidence: f32,

        /// Estimated distance from the camera to the stop line (meters).
        distance_to_stop_line: f32,

        /// Current ego-vehicle speed (mph) at the time of the alert.
        ego_speed: f32,
    },

    /// The intersection ahead is congested and the ego vehicle risks
    /// "blocking the box".
    BlockedIntersection {
        /// Confidence derived from occupancy percentage (0.0 – 1.0).
        confidence: f32,

        /// Percentage of the forward view occupied by vehicles (0 – 100 %).
        occupancy_pct: f32,

        /// Estimated distance to the stop line (meters).
        distance_to_stop_line: f32,

        /// Current ego-vehicle speed (mph).
        ego_speed: f32,
    },
}

// ─────────────────────────────────────────────────────────────────────────────
//  IntersectionAnalyzer
// ─────────────────────────────────────────────────────────────────────────────

/// Analyzes intersection safety from raw YOLO detections.
///
/// Call [`analyze()`](IntersectionAnalyzer::analyze) once per frame with the
/// current detections, ego speed, and frame delta.  The method returns a list
/// of active alerts (may be empty).
pub struct IntersectionAnalyzer {
    /// Intersection-specific thresholds (distances, speeds, grid params).
    config: IntersectionConfig,

    /// Known real-world width of a stop sign in meters.
    ///
    /// US standard stop sign diameter ≈ 30 inches ≈ 0.75 m.
    stop_sign_width_m: f32,

    /// Frame width in pixels (from camera config).
    frame_width: u32,

    /// Frame height in pixels (from camera config).
    frame_height: u32,
}

impl IntersectionAnalyzer {
    /// Constructs a new intersection analyzer.
    ///
    /// # Parameters
    /// - `config` — The top-level pipeline config; only the
    ///   `config.intersection` subset is used.
    ///
    /// # Returns
    /// An `IntersectionAnalyzer` ready to process frames.
    pub fn new(config: &crate::config::Config, frame_width: u32, frame_height: u32) -> Self {
        Self {
            config: config.intersection.clone(),
            stop_sign_width_m: 0.75,
            frame_width,
            frame_height,
        }
    }

    /// Analyzes the current frame for intersection-related alerts.
    ///
    /// # Parameters
    /// - `detections` — Raw detections from the YOLO detector for the
    ///   current frame.
    /// - `ego_speed` — Ego-vehicle speed in **miles per hour**.
    /// - `dt_secs` — Time elapsed since the previous frame (seconds).
    ///   Currently reserved for future temporal filtering.
    ///
    /// # Returns
    /// A `Vec<IntersectionAlert>` — empty if no violation conditions are met.
    ///
    /// # Alert logic (stop sign)
    /// 1. Filter detections for class_id == 0 (stop_sign).
    /// 2. Estimate distance via pinhole: `Z = (f × W) / w`.
    /// 3. If `distance < stop_sign_warning_distance` **and**
    ///    `ego_speed >= stop_sign_warning_speed`, emit `StopSignViolation`.
    ///
    /// # Alert logic (blocked intersection)
    /// 1. Filter detections for vehicle classes (3, 4, 5).
    /// 2. Compute the sum of bounding-box areas as a percentage of the
    ///    total frame area.
    /// 3. If `occupancy > 30%` **and** `ego_speed >= blocked_intersection_speed`,
    ///    emit `BlockedIntersection`.
    pub fn analyze(
        &mut self,
        detections: &[Detection],
        ego_speed: f32,
        dt_secs: f32,
    ) -> Vec<IntersectionAlert> {
        let _ = dt_secs;
        let mut alerts = Vec::new();
        self.check_stop_signs(detections, ego_speed, &mut alerts);
        self.check_blocked_intersection(detections, ego_speed, &mut alerts);
        alerts
    }

    /// Check for stop-sign violations: ego speed too high near a stop sign.
    fn check_stop_signs(
        &self,
        detections: &[Detection],
        ego_speed: f32,
        alerts: &mut Vec<IntersectionAlert>,
    ) {
        const MIN_CONFIDENCE: f32 = 0.5;
        for sign in detections.iter().filter(|d| d.class_id == 0 && d.confidence >= MIN_CONFIDENCE) {
            let pixel_width = (sign.x2 - sign.x1).abs();
            if pixel_width < 1.0 {
                continue;
            }

            let distance = estimate_distance(
                pixel_width,
                self.stop_sign_width_m,
                self.config.stop_sign_warning_distance,
            )
            .clamp(1.0, 200.0);

            if distance <= self.config.stop_sign_warning_distance
                && ego_speed >= self.config.stop_sign_warning_speed
            {
                alerts.push(IntersectionAlert::StopSignViolation {
                    confidence: sign.confidence,
                    distance_to_stop_line: distance,
                    ego_speed,
                });
            }
        }
    }

    /// Check for blocked intersection: high occupancy by vehicles ahead.
    fn check_blocked_intersection(
        &self,
        detections: &[Detection],
        ego_speed: f32,
        alerts: &mut Vec<IntersectionAlert>,
    ) {
        let vehicles: Vec<&Detection> = detections
            .iter()
            .filter(|d| (3..=5).contains(&d.class_id) && d.confidence > 0.4)
            .collect();

        if vehicles.is_empty() {
            return;
        }

        let total_area: f32 = (self.frame_width * self.frame_height) as f32;
        let occupied_area: f32 = vehicles.iter().map(|d| (d.x2 - d.x1) * (d.y2 - d.y1)).sum();
        let occupancy_pct = ((occupied_area / total_area) * 100.0).clamp(0.0, 100.0);

        if occupancy_pct > 30.0 && ego_speed >= self.config.blocked_intersection_speed {
            alerts.push(IntersectionAlert::BlockedIntersection {
                confidence: occupancy_pct / 100.0,
                occupancy_pct,
                distance_to_stop_line: self.config.blocked_distance_to_stop,
                ego_speed,
            });
        }
    }
}

